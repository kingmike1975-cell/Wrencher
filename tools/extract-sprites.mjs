// Pulls the hand-drawn sprite rows and palettes out of the original single-file build (public/index.html)
// into game/src/sprites/data.js, so the Phaser build draws exactly the same pixels.
// Run: node tools/extract-sprites.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const src = readFileSync(new URL('../public/index.html', import.meta.url), 'utf8');

// the literal after `const NAME = `, up to its matching close bracket
function literal(name) {
  // `const NAME = ...` or a second declaration on the same line, `const A = ..., NAME = ...`
  const m = new RegExp(`(?:const|,) ${name} = `).exec(src);
  if (!m) throw new Error(`${name} not found`);
  let i = m.index + m[0].length;
  const open = src[i], close = { '[': ']', '{': '}' }[open];
  if (!close) throw new Error(`${name} is not an array or object literal`);
  let depth = 0, q = null;
  for (let j = i; j < src.length; j++) {
    const c = src[j];
    if (q) { if (c === '\\') j++; else if (c === q) q = null; continue; }
    if (c === "'" || c === '"' || c === '`') q = c;
    else if (c === open) depth++;
    else if (c === close && --depth === 0) return src.slice(i, j + 1);
  }
  throw new Error(`${name} never closes`);
}
// the object literal passed to wrenRows(WREN_HD, {...}) for a derived sprite
function wrenRowsArg(name) {
  const m = src.match(new RegExp(`const ${name} = wrenRows\\(WREN_HD, (\\{[^}]*\\})\\)`));
  if (!m) throw new Error(`${name} not found`);
  return m[1];
}

const names = ['WPAL', 'TRACK_COLS', 'USHANKA_COLS', 'RANKS', 'GIRDER_PALS', 'FY', 'LADDERS', 'PIPES', 'MPOS', 'SMALL_POS',
  'WREN_HD', 'WREN_HD_NOFRONT', 'WREN_HD_BACK', 'WREN_HD_SLING', 'USH_TOP', 'BUR_HD', 'BUR2_HD'];
const out = {};
for (const n of names) out[n] = vm.runInNewContext(`(${literal(n)})`);
out.WREN_HD_NOARMS_AT = vm.runInNewContext(`(${wrenRowsArg('WREN_NOARMS_HD')})`);
// WREN2_HD is WREN_HD's first 24 rows plus four walking-leg rows
const legs = src.match(/const WREN2_HD = WREN_HD\.slice\(0, 24\)\.concat\((\[[^\]]*\])\)/);
out.WREN2_HD_LEGS = vm.runInNewContext(`(${legs[1]})`);
// the per-sprite shade letters (extra 2x colours worked out from a base palette letter)
const shade = src.match(/\[WREN, \{rows:WREN_HD, shade:(\{[^}]*\})\}\]/);
out.WREN_SHADE = vm.runInNewContext(`(${shade[1]})`);
const burShade = src.match(/\[BUR, \{rows:BUR_HD, shade:(\{[^}]*\})\}\]/);
out.BUR_SHADE = vm.runInNewContext(`(${burShade[1]})`);
out.WPAL_HOT_S = src.match(/const WPAL_HOT = Object\.assign\(\{\}, WPAL, \{s:'(#[0-9a-f]+)'\}\)/)[1];

let js = '// GENERATED by tools/extract-sprites.mjs from public/index.html. Do not edit by hand.\n';
for (const [k, v] of Object.entries(out)) js += `export const ${k} = ${JSON.stringify(v)};\n`;
// the bureaucrat palette maker is a function; copy its source as is
js += `export ${src.match(/const burPal = .*;/)[0]}\n`;
writeFileSync(new URL('../game/src/sprites/data.js', import.meta.url), js);
console.log('wrote game/src/sprites/data.js:', Object.keys(out).join(', '));
