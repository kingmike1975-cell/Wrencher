// Pulls the world constants, voice-line text, sprite rows and palettes out of the original single-file build
// (public/index.html) into game/src/sprites/data.js, so the Phaser build uses exactly the same numbers and pixels.
// It runs those sections of the original in a sandbox and writes every plain value they define.
// Run: npm run sprites
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const src = readFileSync(new URL('../public/index.html', import.meta.url), 'utf8');
const lines = src.split('\n');
// a section runs from its "// ---------- name" header to the next header
function section(startsWith) {
  const a = lines.findIndex(l => l.startsWith('// ---------- ' + startsWith));
  if (a < 0) throw new Error(`section "${startsWith}" not found`);
  const b = lines.findIndex((l, i) => i > a && l.startsWith('// ---------- '));
  return lines.slice(a, b).join('\n');
}
// the 2x section ends with the drawing helper spr(), which needs the canvas; stop just before it
const hd = section('hand-drawn 2x sprites').split('\nfunction spr(')[0];
const code = [section('world constants'), section('nuclear plant (round 4 on)'), section('lines (placeholders'), section('sprites'), hd].join('\n');

const names = new Set();
for (const m of code.matchAll(/^(?:const|let) ([A-Za-z_$][\w$]*)/gm)) names.add(m[1]);
for (const m of code.matchAll(/^(?:const|let) [^\n]*?(?:\]|\}|\d|'|"|\)), ([A-Z_][\w$]*) = /gm)) names.add(m[1]);

const ctx = vm.createContext({});
vm.runInContext(code + `\n;globalThis.__out = {${[...names].map(n => `${n}: typeof ${n} === 'undefined' ? undefined : ${n}`).join(',')}};`, ctx);
const out = ctx.__out;

// HD_SPRITES maps each 1x sprite (by identity) to its hand-drawn 2x rows; store it by name instead
const nameOf = new Map();
for (const [k, v] of Object.entries(out)) if (Array.isArray(v)) nameOf.set(v, k);
const hdList = [];
for (const [low, entry] of out.HD_SPRITES) hdList.push([nameOf.get(low), nameOf.get(entry.rows) || entry.rows, entry.shade]);

let js = '// GENERATED by tools/extract-sprites.mjs from public/index.html. Do not edit by hand.\n';
let n = 0;
for (const [k, v] of Object.entries(out)) {
  if (v === undefined || typeof v === 'function' || v instanceof vm.runInContext('WeakMap', ctx) || k === 'HD_SPRITES' || k === 'HD_PALS' || k === 'S2X' || k === 'USH') continue;
  js += `export const ${k} = ${JSON.stringify(v)};\n`; n++;
}
js += `// [1x sprite, 2x rows (name or rows), shade letters]\nexport const HD_LIST = ${JSON.stringify(hdList)};\n`;
// outfit colours live in the kiosk section; copy just those two
js += `export ${src.match(/const TRACK_COLS = \{[^}]*\}, USHANKA_COLS = \{[^}]*\};/)[0]}\n`;
// functions the sprite data relies on, copied as source
for (const f of ['wrenRows', 'burPal']) js += `export ${src.match(new RegExp(`const ${f} = .*;`))[0]}\n`;
writeFileSync(new URL('../game/src/sprites/data.js', import.meta.url), js);
console.log(`wrote game/src/sprites/data.js: ${n} values, ${hdList.length} 2x sprites`);
