// Builds game/src/legacy/game.js: the original single-file game (public/index.html) as an ES module that runs inside
// the Phaser build. Phaser takes over the game loop, the on-screen controls and putting the world on screen;
// everything else (rules, levels, art, sound, cards) is the original code, unchanged.
// Run after changing public/index.html: npm run legacy
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const html = readFileSync(new URL('../public/index.html', import.meta.url), 'utf8');
let js = html.slice(html.indexOf('<script>') + 8, html.lastIndexOf('</script>'));

// each patch must match exactly once, so a change to the original that breaks one stops the build loudly
function patch(name, from, to) {
  const n = js.split(from).length - 1;
  if (n !== 1) throw new Error(`patch "${name}": expected 1 match, found ${n}`);
  js = js.replace(from, to);
}
function patchBetween(name, startMarker, endMarker, to) {
  const a = js.indexOf(startMarker), b = js.indexOf(endMarker, a);
  if (a < 0 || b < 0) throw new Error(`patch "${name}": markers not found`);
  js = js.slice(0, a) + to + js.slice(b);
}

// the whole game was one immediately-run function; make it a function the Phaser scene starts
if (!js.startsWith('\n(() => {\n')) throw new Error('patch "open": the script no longer starts with (() => {');
js = '\nexport function startLegacy(host) {\n' + js.slice('\n(() => {\n'.length);
patch('close', '\nrequestAnimationFrame(frame);\n})();', `
return {
  frame, G, cam, inp,
  view: () => ({ fit, dx0, dy0, dw, dh, dpr, cw, ch, PXD }),
  toggleMute: () => { ensureAudio(); toggleMute(); },
};
}`);

// the screen canvas (text, bubbles, HUD) and the world buffer are handed in by the scene
patch('screen canvas', "const cv = document.getElementById('cv'), ctx = cv.getContext('2d');", 'const cv = host.screenCanvas, ctx = cv.getContext(\'2d\');');
patch('world canvas', "const buf = document.createElement('canvas');", 'const buf = host.worldCanvas;');

// input: the DOM stick, wrench button, keyboard and gamepad code is replaced by Phaser's (game/src/input/Controls.js),
// which keeps the same deadzones and hysteresis. Sound-toggle and start keys are kept.
patchBetween('input', '// ---------- input ----------', '// ---------- game state ----------', `// ---------- input (from Phaser: game/src/input/Controls.js) ----------
const inp = {dx:0, dy:0, vx:0, vy:0, act:false, pressed:false};
window.addEventListener('keydown', e => {
  if (['ArrowLeft','ArrowRight','ArrowUp','ArrowDown','Space'].includes(e.code)) e.preventDefault();
  if (e.code === 'KeyM' && !e.repeat){ ensureAudio(); toggleMute(); }
});
function readInput(){
  const c = host.controls;
  c.update();
  inp.vx = c.vx; inp.vy = c.vy; inp.dx = c.dx; inp.dy = c.dy; inp.act = c.act;
  if (c.pressed){ ensureAudio(); inp.pressed = true; }
  // controller Start presses a card's GO button, Select toggles the sound
  if (c.startPressed){ ensureAudio(); const go = !overlay.hidden && overlay.querySelector('#go'); if (go) go.click(); }
  if (c.selectPressed){ ensureAudio(); toggleMute(); }
}

`);

// sound files live beside the original at /audio/, one folder up from /next/
patch('audio path', 'function loadClip(url){ return fetch(url)', "function loadClip(url){ return fetch((host.assetBase || '') + url)");

// let the playtests read Wrencher's state too
patch('test hook', 'window.__wrencher = {G, ', 'window.__wrencher = {get P(){ return P; }, G, ');

// the loop: Phaser calls frame() every tick instead of requestAnimationFrame
patch('loop', '  inp.pressed = false;\n  requestAnimationFrame(frame);\n}', '  inp.pressed = false;\n}');

// the world buffer goes on screen through Phaser's camera, so render() only clears the text layer and skips the copy
patch('clear', "  ctx.fillStyle = '#07060a'; ctx.fillRect(0, 0, cw, ch);", '  ctx.clearRect(0, 0, cw, ch);');
patch('blit', '  ctx.drawImage(buf, sx*PXD, sy*PXD, vw*PXD, vh*PXD, dx0, dy0, dw, dh);\n', '');

mkdirSync(new URL('../game/src/legacy/', import.meta.url), { recursive: true });
writeFileSync(new URL('../game/src/legacy/game.js', import.meta.url),
  '// GENERATED by tools/make-legacy.mjs from public/index.html. Do not edit by hand; change the original and re-run.\n/* eslint-disable */\n' + js);
console.log('wrote game/src/legacy/game.js');
